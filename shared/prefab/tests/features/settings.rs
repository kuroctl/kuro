//! Réglages saisis : validés contre les champs du prefab, erreur rattachée au champ.

use kuro_prefab::settings::{Reason, SettingError, apply, defaults};
use serde_json::{Map, Value, json};

use crate::support::official;

fn input(value: Value) -> Map<String, Value> {
    value.as_object().unwrap().clone()
}

fn errors(
    result: Result<kuro_prefab::settings::Values, Vec<SettingError>>,
) -> Vec<(String, Reason)> {
    result
        .unwrap_err()
        .into_iter()
        .map(|e| (e.field, e.reason))
        .collect()
}

#[test]
fn deployment_starts_from_the_defaults() {
    let manifest = official("minecraft-java").manifest;

    let values = apply(&manifest, None, &input(json!({ "motd": "Bienvenue" }))).unwrap();

    assert_eq!(values["motd"], json!("Bienvenue"));
    assert_eq!(values["max_players"], json!(20));
    assert_eq!(values["loader"], json!("vanilla"));
    assert!(
        !values.contains_key("rcon_password"),
        "secrets are generated by the caller"
    );
}

#[test]
fn invalid_values_are_reported_per_field() {
    let manifest = official("minecraft-java").manifest;

    let result = apply(
        &manifest,
        None,
        &input(json!({
            "max_players": 0,
            "view_distance": 99,
            "difficulty": "nightmare",
            "version": "1.x",
            "pvp": "yes",
            "motd": "x".repeat(60),
            "teleport": true
        })),
    );

    let mut found = errors(result);
    found.sort();
    let mut expected = vec![
        ("max_players".to_owned(), Reason::Min),
        ("view_distance".to_owned(), Reason::Max),
        ("difficulty".to_owned(), Reason::Options),
        ("version".to_owned(), Reason::Pattern),
        ("pvp".to_owned(), Reason::Type),
        ("motd".to_owned(), Reason::MaxLength),
        ("teleport".to_owned(), Reason::UnknownField),
    ];
    expected.sort();
    assert_eq!(found, expected);
}

#[test]
fn a_line_break_cannot_inject_a_configuration_line() {
    let manifest = official("minecraft-java").manifest;

    let result = apply(
        &manifest,
        None,
        &input(json!({ "motd": "hi\nop-permission-level=4" })),
    );

    assert_eq!(
        errors(result),
        vec![("motd".to_owned(), Reason::ControlCharacter)]
    );
}

#[test]
fn a_text_field_accepts_several_lines() {
    let manifest = official("wordpress").manifest;

    let values = apply(
        &manifest,
        None,
        &input(json!({ "config_extra": "define('WP_CACHE', true);\ndefine('WP_MEMORY_LIMIT', '256M');" })),
    )
    .unwrap();

    assert!(values["config_extra"].as_str().unwrap().contains('\n'));
}

#[test]
fn a_deploy_only_field_is_frozen_afterwards() {
    let manifest = official("minecraft-java").manifest;
    let deployed = apply(&manifest, None, &input(json!({ "loader": "fabric" }))).unwrap();

    let change = apply(
        &manifest,
        Some(&deployed),
        &input(json!({ "loader": "forge" })),
    );
    let same = apply(
        &manifest,
        Some(&deployed),
        &input(json!({ "loader": "fabric", "motd": "x" })),
    );

    assert_eq!(
        errors(change),
        vec![("loader".to_owned(), Reason::NotEditable)]
    );
    assert!(same.is_ok());
}

#[test]
fn null_resets_to_the_default() {
    let manifest = official("minecraft-java").manifest;
    let deployed = apply(&manifest, None, &input(json!({ "max_players": 50 }))).unwrap();

    let reset = apply(
        &manifest,
        Some(&deployed),
        &input(json!({ "max_players": null })),
    )
    .unwrap();

    assert_eq!(reset["max_players"], defaults(&manifest)["max_players"]);
}

#[test]
fn required_fields_cannot_be_emptied() {
    let manifest = official("ark-survival-ascended").manifest;

    let result = apply(&manifest, None, &input(json!({ "session_name": "" })));

    assert_eq!(
        errors(result),
        vec![("session_name".to_owned(), Reason::Required)]
    );
}

mod migrate {
    use std::collections::BTreeMap;

    use kuro_prefab::manifest::Migration;
    use kuro_prefab::settings::{Reason, Values, migrate};
    use serde_json::json;

    use crate::support::official;

    fn version(text: &str) -> semver::Version {
        text.parse().unwrap()
    }

    /// Réglages enregistrés sous une version où `motd` s'appelait `message` et où existait
    /// `legacy`.
    fn stored() -> Values {
        Values::from([
            ("message".to_owned(), json!("Bienvenue")),
            ("legacy".to_owned(), json!(true)),
            ("difficulty".to_owned(), json!("hard")),
        ])
    }

    fn migration(from: &str) -> Migration {
        Migration {
            from: from.to_owned(),
            rename: BTreeMap::from([("message".to_owned(), "motd".to_owned())]),
            remove: vec!["legacy".to_owned()],
        }
    }

    #[test]
    fn matching_migrations_rename_remove_and_defaults_fill_the_rest() {
        let mut manifest = official("minecraft-java").manifest;
        manifest.migrations.push(migration("<1.1.0"));
        let migrated = migrate(&version("1.0.0"), &manifest, &stored()).unwrap();

        assert_eq!(migrated.values["motd"], json!("Bienvenue"));
        assert_eq!(migrated.values["difficulty"], json!("hard"));
        assert!(!migrated.values.contains_key("legacy"));
        assert_eq!(
            migrated.renamed,
            [("message".to_owned(), "motd".to_owned())]
        );
        assert_eq!(migrated.removed, ["legacy"]);
        assert!(migrated.added.contains(&"max_players".to_owned()));
    }

    #[test]
    fn a_migration_for_other_versions_is_skipped() {
        let mut manifest = official("minecraft-java").manifest;
        manifest.migrations.push(migration("<1.0.0"));
        let migrated = migrate(&version("1.0.0"), &manifest, &stored()).unwrap();
        // Pas de renommage : `message` est inconnue, donc retirée, et `motd` prend son défaut.
        assert!(migrated.renamed.is_empty());
        assert!(migrated.removed.contains(&"message".to_owned()));
        assert_eq!(migrated.values["motd"], json!("A Kuro server"));
    }

    #[test]
    fn a_value_no_longer_valid_blocks_the_upgrade() {
        let manifest = official("minecraft-java").manifest;
        let current = Values::from([("difficulty".to_owned(), json!("nightmare"))]);
        let errors = migrate(&version("1.0.0"), &manifest, &current).unwrap_err();
        assert_eq!(errors[0].field, "difficulty");
        assert_eq!(errors[0].reason, Reason::Options);
    }
}
